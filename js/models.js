export const modelsFor = (make) => {
  const m = String(make || '').trim();
  return MODELS[m] || MODELS[Object.keys(MODELS).find((k) => k.replace(/\s/g, '') === m.replace(/\s/g, ''))] || [];
};

// Any form with a make field: the model suggestions follow the chosen make
let wired = false;
export function wireModels() {
  if (wired) return; wired = true;
  const sync = (e) => {
    const mk = e.target.closest?.('[name="make"]');
    if (!mk) return;
    const form = mk.form || mk.closest('form,dialog,section') || document;
    const dl = form.querySelector('datalist[data-models]') || document.querySelector('datalist[data-models]');
    if (dl) dl.innerHTML = modelsFor(mk.value).map((x) => `<option value="${x.replace(/"/g, '&quot;')}">`).join('');
  };
  document.addEventListener('input', sync);
  document.addEventListener('change', sync);
}
