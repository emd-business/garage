// Fill a template: unknown or empty placeholders disappear, and doubled spaces are tidied.
export function waText(key, vars) {
  const custom = ctx.garage?.wa_templates?.[key];
  const tpl = typeof custom === 'string' && custom.trim() ? custom : WA[key].def;
  return tpl.replace(/\{([^{}]+)\}/g, (_, k) => String(vars[k.trim()] ?? ''))
    .replace(/[ \t]{2,}/g, ' ').replace(/ +([.،,])/g, '$1').trim();
}
